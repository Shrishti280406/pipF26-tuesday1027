-- Schema derived from class_dataset.csv (34 student survey rows).
-- Multi-valued CSV columns (tools, availability) are stored as many-to-many
-- relationships; remaining fields stay on students.

CREATE TABLE students (
    netid                   VARCHAR(16) PRIMARY KEY,
    name                    VARCHAR(64) NOT NULL,
    school_year             VARCHAR(16) NOT NULL
        CHECK (school_year IN ('Sophomore', 'Junior', 'Senior')),
    intro_programming       VARCHAR(16) NOT NULL
        CHECK (intro_programming IN ('took_it', 'equivalent', 'neither')),
    skill_programming       INTEGER NOT NULL
        CHECK (skill_programming BETWEEN 1 AND 5),
    skill_data_stats        INTEGER NOT NULL
        CHECK (skill_data_stats BETWEEN 1 AND 5),
    skill_frontend_design   INTEGER NOT NULL
        CHECK (skill_frontend_design BETWEEN 1 AND 5),
    skill_business_pitch    INTEGER NOT NULL
        CHECK (skill_business_pitch BETWEEN 1 AND 5),
    working_style           TEXT NOT NULL,
    interests               TEXT NOT NULL,
    semester_goal           TEXT NOT NULL,
    submitted_at            TIMESTAMPTZ NOT NULL
);

CREATE TABLE tools (
    tool_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tool_name   VARCHAR(32) NOT NULL UNIQUE
);

CREATE TABLE student_tools (
    netid       VARCHAR(16) NOT NULL
        REFERENCES students (netid) ON DELETE CASCADE,
    tool_id     INTEGER NOT NULL
        REFERENCES tools (tool_id) ON DELETE RESTRICT,
    PRIMARY KEY (netid, tool_id)
);

CREATE TABLE availability_slots (
    slot_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slot_name   VARCHAR(32) NOT NULL UNIQUE
);

CREATE TABLE student_availability (
    netid       VARCHAR(16) NOT NULL
        REFERENCES students (netid) ON DELETE CASCADE,
    slot_id     INTEGER NOT NULL
        REFERENCES availability_slots (slot_id) ON DELETE RESTRICT,
    PRIMARY KEY (netid, slot_id)
);
